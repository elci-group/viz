//! Deterministic VHS tape composition and persistence.

use crate::error::{Error, Result};
use crate::model::{CommandCandidate, Project, ProjectKind};
use std::fmt::Write as _;
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};

/// Presentation settings and command overrides for a generated tape.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TapeOptions {
    /// Media path written to the VHS `Output` directive.
    pub media_output: String,
    /// Optional presentation title; defaults to the project name.
    pub title: Option<String>,
    /// Explicit commands, used instead of inferred candidates when non-empty.
    pub commands: Vec<String>,
    /// Directory entered before recording, relative to the tape when possible.
    pub working_directory: Option<PathBuf>,
    /// Include every inferred command rather than only the highest-ranked one.
    pub include_all: bool,
    /// Terminal width in pixels.
    pub width: u16,
    /// Terminal height in pixels.
    pub height: u16,
    /// Terminal font size in pixels.
    pub font_size: u8,
    /// Delay per typed character in milliseconds.
    pub typing_speed_ms: u16,
}

impl Default for TapeOptions {
    fn default() -> Self {
        Self {
            media_output: "demo.gif".into(),
            title: None,
            commands: Vec::new(),
            working_directory: None,
            include_all: false,
            width: 1200,
            height: 720,
            font_size: 18,
            typing_speed_ms: 35,
        }
    }
}

/// Generates deterministic VHS source from inspected project evidence.
///
/// # Errors
///
/// Returns an error for unsafe commands, invalid presentation settings, or an
/// inspection result without a usable command.
pub fn generate_tape(project: &Project, options: &TapeOptions) -> Result<String> {
    validate_options(options)?;
    let commands = selected_commands(project, options)?;
    let title = options.title.as_deref().unwrap_or(&project.name);
    let requirement = required_program(project.kind, &commands[0], options.commands.is_empty());
    let mut tape = String::new();

    tape.push_str("# Generated by viz. Review commands before rendering.\n");
    let _ignored = writeln!(
        tape,
        "# Project: {} ({})",
        comment_text(&project.name),
        project.kind
    );
    for evidence in &project.evidence {
        let location = evidence.line.map_or_else(
            || evidence.source.display().to_string(),
            |line| format!("{}:{line}", evidence.source.display()),
        );
        let _ignored = writeln!(
            tape,
            "# Evidence: {} — {}",
            comment_text(&location),
            comment_text(&evidence.fact)
        );
    }
    tape.push('\n');
    let _ignored = writeln!(tape, "Output {}", options.media_output);
    if let Some(program) = requirement {
        let _ignored = writeln!(tape, "Require {program}");
    }
    tape.push_str("\nSet Shell \"bash\"\n");
    let _ignored = writeln!(tape, "Set FontSize {}", options.font_size);
    let _ignored = writeln!(tape, "Set Width {}", options.width);
    let _ignored = writeln!(tape, "Set Height {}", options.height);
    tape.push_str("Set Padding 24\n");
    let _ignored = writeln!(tape, "Set TypingSpeed {}ms\n", options.typing_speed_ms);
    tape.push_str("Hide\n");
    if let Some(directory) = &options.working_directory {
        let directory = directory.to_string_lossy();
        let change_directory = format!("cd -- {}", shell_quote(&directory));
        let _ignored = writeln!(tape, "Type \"{}\"", escape_vhs(&change_directory));
        tape.push_str("Enter\n");
    }
    tape.push_str("Type \"clear\"\nEnter\nShow\nSleep 500ms\n\n");
    let _ignored = writeln!(
        tape,
        "Type \"# {} — {} project\"\nEnter\nSleep 750ms\n",
        escape_vhs(title),
        project.kind
    );
    for (index, command) in commands.iter().enumerate() {
        if index > 0 {
            tape.push_str("Sleep 1s\n\n");
        }
        let _ignored = writeln!(tape, "Type \"{}\"", escape_vhs(command));
        tape.push_str("Enter\nSleep 3s\n");
    }

    Ok(tape)
}

/// Writes a tape, refusing accidental replacement unless `force` is true.
///
/// # Errors
///
/// Returns an error when the destination exists without `force`, or when a
/// create, write, sync, or atomic replacement operation fails.
pub fn write_tape(path: &Path, content: &str, force: bool) -> Result<()> {
    if !force {
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(path)
            .map_err(|error| {
                if error.kind() == std::io::ErrorKind::AlreadyExists {
                    Error::OutputExists(path.to_path_buf())
                } else {
                    Error::io("create", path, error)
                }
            })?;
        file.write_all(content.as_bytes())
            .map_err(|error| Error::io("write", path, error))?;
        file.sync_all()
            .map_err(|error| Error::io("sync", path, error))?;
        return Ok(());
    }

    let temporary = temporary_path(path);
    let result = (|| {
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temporary)
            .map_err(|error| Error::io("create", &temporary, error))?;
        file.write_all(content.as_bytes())
            .map_err(|error| Error::io("write", &temporary, error))?;
        file.sync_all()
            .map_err(|error| Error::io("sync", &temporary, error))?;
        fs::rename(&temporary, path).map_err(|error| Error::io("replace", path, error))
    })();
    if result.is_err() {
        let _ignored = fs::remove_file(&temporary);
    }
    result
}

/// Performs a cheap structural check before invoking an external VHS parser.
///
/// # Errors
///
/// Returns an error when required directives are absent.
pub fn validate_tape_source(source: &str) -> Result<()> {
    if source.trim().is_empty() {
        return Err(Error::Inspection("tape is empty".into()));
    }
    for required in ["Output ", "Set Shell ", "Type ", "Enter"] {
        if !source.lines().any(|line| line.starts_with(required)) {
            return Err(Error::Inspection(format!(
                "tape is missing required `{}` directive",
                required.trim()
            )));
        }
    }
    Ok(())
}

fn selected_commands(project: &Project, options: &TapeOptions) -> Result<Vec<String>> {
    let commands = if options.commands.is_empty() {
        if options.include_all {
            project
                .commands
                .iter()
                .map(|candidate| candidate.command.clone())
                .collect()
        } else {
            project
                .commands
                .first()
                .map(|candidate| vec![candidate.command.clone()])
                .unwrap_or_default()
        }
    } else {
        options.commands.clone()
    };
    if commands.is_empty() {
        return Err(Error::Inspection(
            "no demonstration command could be inferred; pass --command".into(),
        ));
    }
    for command in &commands {
        if command.trim().is_empty() {
            return Err(Error::Usage(
                "demonstration commands cannot be empty".into(),
            ));
        }
        if command
            .chars()
            .any(|character| matches!(character, '\n' | '\r' | '\0'))
        {
            return Err(Error::Usage(
                "demonstration commands must occupy one line".into(),
            ));
        }
    }
    Ok(commands)
}

fn validate_options(options: &TapeOptions) -> Result<()> {
    if options.width < 320 || options.height < 200 {
        return Err(Error::Usage(
            "terminal dimensions must be at least 320x200".into(),
        ));
    }
    if !(8..=72).contains(&options.font_size) {
        return Err(Error::Usage("font size must be between 8 and 72".into()));
    }
    if options.typing_speed_ms > 2_000 {
        return Err(Error::Usage(
            "typing speed must be no more than 2000ms".into(),
        ));
    }
    if options.title.as_ref().is_some_and(|title| {
        title
            .chars()
            .any(|character| matches!(character, '\n' | '\r' | '\0'))
    }) {
        return Err(Error::Usage("title must occupy one line".into()));
    }
    if options.working_directory.as_ref().is_some_and(|path| {
        path.to_string_lossy()
            .chars()
            .any(|character| matches!(character, '\n' | '\r' | '\0'))
    }) {
        return Err(Error::Usage(
            "working directory must occupy one line".into(),
        ));
    }
    let media = Path::new(&options.media_output);
    if options.media_output.is_empty()
        || options.media_output.chars().any(|character| {
            !(character.is_ascii_alphanumeric() || matches!(character, '/' | '.' | '_' | '-'))
        })
    {
        return Err(Error::Usage(
            "media output must be a non-empty path without whitespace".into(),
        ));
    }
    let supported = media
        .extension()
        .and_then(|extension| extension.to_str())
        .is_some_and(|extension| matches!(extension, "gif" | "mp4" | "webm"));
    if !supported {
        return Err(Error::Usage(
            "media output must end in .gif, .mp4, or .webm".into(),
        ));
    }
    Ok(())
}

fn required_program(
    kind: ProjectKind,
    primary: &str,
    allow_ecosystem_fallback: bool,
) -> Option<&'static str> {
    let token = primary.split_whitespace().next()?;
    match token {
        "cargo" => Some("cargo"),
        "npm" => Some("npm"),
        "pnpm" => Some("pnpm"),
        "yarn" => Some("yarn"),
        "bun" => Some("bun"),
        "python" | "python3" => Some("python"),
        "go" => Some("go"),
        "make" => Some("make"),
        _ if allow_ecosystem_fallback => match kind {
            ProjectKind::Rust => Some("cargo"),
            ProjectKind::Node => Some("npm"),
            ProjectKind::Python => Some("python"),
            ProjectKind::Go => Some("go"),
            ProjectKind::Generic => None,
        },
        _ => None,
    }
}

fn escape_vhs(input: &str) -> String {
    input.replace('\\', "\\\\").replace('"', "\\\"")
}

fn shell_quote(input: &str) -> String {
    format!("'{}'", input.replace('\'', "'\"'\"'"))
}

fn comment_text(input: &str) -> String {
    input.replace(['\n', '\r'], " ")
}

fn temporary_path(path: &Path) -> PathBuf {
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("tape");
    path.with_file_name(format!(".{file_name}.viz-{}.tmp", std::process::id()))
}

/// Formats an inferred candidate for human-readable planning output.
#[must_use]
pub fn describe_candidate(candidate: &CommandCandidate) -> String {
    format!(
        "[{}%] {}\n       {}",
        candidate.confidence, candidate.command, candidate.reason
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Evidence, Project};

    fn project() -> Project {
        Project {
            root: PathBuf::from("/work/comet"),
            name: "comet".into(),
            kind: ProjectKind::Rust,
            evidence: vec![Evidence {
                source: PathBuf::from("Cargo.toml"),
                line: Some(2),
                fact: "Cargo package `comet`".into(),
            }],
            commands: vec![CommandCandidate {
                command: "cargo run -- --help".into(),
                reason: "show help".into(),
                confidence: 95,
            }],
        }
    }

    #[test]
    fn generation_is_deterministic_and_contains_provenance() {
        let first = generate_tape(&project(), &TapeOptions::default()).expect("generate tape");
        let second = generate_tape(&project(), &TapeOptions::default()).expect("generate tape");
        assert_eq!(first, second);
        assert!(first.contains("# Evidence: Cargo.toml:2"));
        assert!(first.contains("Require cargo"));
        assert!(first.contains("Type \"cargo run -- --help\""));
    }

    #[test]
    fn escapes_quotes_and_backslashes_in_commands() {
        let options = TapeOptions {
            commands: vec![r#"printf "%s" C:\tmp"#.into()],
            ..TapeOptions::default()
        };
        let tape = generate_tape(&project(), &options).expect("generate escaped tape");
        assert!(tape.contains(r#"Type "printf \"%s\" C:\\tmp""#));
    }

    #[test]
    fn rejects_multiline_commands() {
        let options = TapeOptions {
            commands: vec!["echo safe\nrm file".into()],
            ..TapeOptions::default()
        };
        assert!(generate_tape(&project(), &options).is_err());
    }

    #[test]
    fn structural_validation_rejects_incomplete_tapes() {
        assert!(validate_tape_source("Output demo.gif\n").is_err());
    }

    #[test]
    fn custom_command_does_not_invent_an_ecosystem_requirement() {
        let options = TapeOptions {
            commands: vec!["echo hello".into()],
            ..TapeOptions::default()
        };
        let tape = generate_tape(&project(), &options).expect("generate custom tape");
        assert!(!tape.contains("Require cargo"));
    }

    #[test]
    fn rejects_directive_breaking_titles_and_media_paths() {
        let title = TapeOptions {
            title: Some("safe\nType \"bad\"".into()),
            ..TapeOptions::default()
        };
        let media = TapeOptions {
            media_output: "demo #1.gif".into(),
            ..TapeOptions::default()
        };
        assert!(generate_tape(&project(), &title).is_err());
        assert!(generate_tape(&project(), &media).is_err());
    }

    #[test]
    fn hidden_setup_safely_enters_the_project_directory() {
        let options = TapeOptions {
            working_directory: Some(PathBuf::from("../project's source")),
            ..TapeOptions::default()
        };
        let tape = generate_tape(&project(), &options).expect("generate tape with setup");
        assert!(tape.contains(r#"Type "cd -- '../project'\"'\"'s source'""#));
        assert!(tape.find("cd --").expect("cd command") < tape.find("Show").expect("Show"));
    }
}
